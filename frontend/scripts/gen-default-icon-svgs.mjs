#!/usr/bin/env node
// Generates src/defaultIconSvgs.generated.ts from
// src/defaultIconNames.json -- the curated icon set IconPicker.tsx's
// "Icons" tab shows by default (no search query yet).
//
// Why generated rather than fetched at runtime: the Icons tab used to
// render even this curated ~165-icon default view as <img src> against
// separate static files, same as the full ~2000-icon library. That
// still meant ~165 near-simultaneous network requests every time the
// tab opened -- fewer than before, but still enough to feel jittery against the browser's per-origin HTTP/1.1 connection
// limit. Notion's equivalent picker doesn't fetch its default set
// either -- it ships baked in. This script does the same: read each
// curated icon's real SVG markup out of the pinned lucide-static
// version and bake it directly into a TS module, so the default view
// renders instantly with zero network requests. Anything beyond the
// default 165 (reached via search) still loads from real files --
// baking all ~2000 in would bloat the bundle for icons most sessions
// never see.
//
// Run after editing src/defaultIconNames.json, or after bumping
// lucide-static to a new pinned version:
//   node scripts/gen-default-icon-svgs.mjs

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const here = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(here, '..')

const names = JSON.parse(readFileSync(path.join(root, 'src/defaultIconNames.json'), 'utf8'))

const entries = names.map((name) => {
  const svgPath = path.join(root, 'node_modules/lucide-static/icons', `${name}.svg`)
  let svg = readFileSync(svgPath, 'utf8')
  // Strip the per-file license comment (identical across every
  // lucide-static icon, and the package's own LICENSE file already
  // covers this) -- pure size trim, ~165 of these add up.
  svg = svg.replace(/<!--[\s\S]*?-->\s*/, '').trim()
  return [name, svg]
})

const lines = entries.map(
  ([name, svg]) => `  ${JSON.stringify(name)}: ${JSON.stringify(svg)},`,
)

const out = `// GENERATED by scripts/gen-default-icon-svgs.mjs -- do not hand-edit.
// Source: src/defaultIconNames.json + the pinned lucide-static version
// (see package.json). Regenerate with:
//   node scripts/gen-default-icon-svgs.mjs
//
// Raw <svg>...</svg> markup for IconPicker.tsx's default (no search
// query) Icons-tab grid, baked in at build time instead of fetched --
// see this script's own header comment for why.
export const DEFAULT_ICON_SVGS: Record<string, string> = {
${lines.join('\n')}
}
`

writeFileSync(path.join(root, 'src/defaultIconSvgs.generated.ts'), out)
console.log(`Wrote src/defaultIconSvgs.generated.ts (${entries.length} icons)`)
