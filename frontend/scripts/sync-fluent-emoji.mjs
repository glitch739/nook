#!/usr/bin/env node
// Copies the Fluent Emoji 3D images (Microsoft, MIT, via the
// @lobehub/fluent-emoji-3d package) for every emoji in
// src/emojiData.ts into src/emoji/, and writes
// src/fluentEmoji.generated.ts: emoji character -> image file name.
//
// Only the curated set is copied (~200 small WebP files, ~2 MB), not the
// package's ~3400 (18 MB): page icons can only be picked from that set.
// Images are served by Nook itself, no third-party CDN. They live under
// src/ (not public/) so Vite gives them content-hashed /assets/ URLs,
// which the server caches forever (Emoji.tsx resolves them).
//
// Run after editing src/emojiData.ts or updating the package:
//   node scripts/sync-fluent-emoji.mjs

import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const assets = join(root, 'node_modules/@lobehub/fluent-emoji-3d/assets')
const outDir = join(root, 'src/emoji')
const outMap = join(root, 'src/fluentEmoji.generated.ts')

if (!existsSync(assets)) {
  console.error('missing @lobehub/fluent-emoji-3d: run npm install first')
  process.exit(1)
}
const available = new Set(readdirSync(assets))
const chars = [...readFileSync(join(root, 'src/emojiData.ts'), 'utf8').matchAll(/char: '([^']+)'/g)].map((m) => m[1])

// The package names files by lowercase code points joined with "-";
// some keep the U+FE0F variation selector, some drop it.
function fileFor(ch) {
  const cps = [...ch].map((c) => c.codePointAt(0).toString(16))
  for (const name of [cps.join('-'), cps.filter((c) => c !== 'fe0f').join('-')]) {
    if (available.has(`${name}.webp`)) return `${name}.webp`
  }
  return null
}

rmSync(outDir, { recursive: true, force: true })
mkdirSync(outDir, { recursive: true })
const map = {}
const missing = []
for (const ch of new Set(chars)) {
  const file = fileFor(ch)
  if (!file) {
    missing.push(ch)
    continue
  }
  copyFileSync(join(assets, file), join(outDir, file))
  map[ch] = file
}

writeFileSync(
  outMap,
  `// Generated by scripts/sync-fluent-emoji.mjs -- do not edit by hand.
// Emoji character -> Fluent Emoji 3D image in src/emoji/.
export const FLUENT_EMOJI: Record<string, string> = ${JSON.stringify(map, null, 2)}
`,
)
console.log(`copied ${Object.keys(map).length} images to src/emoji/`)
if (missing.length) console.log(`no Fluent image (shown as native emoji): ${missing.join(' ')}`)
